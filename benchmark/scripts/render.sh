#!/usr/bin/env bash
# Renders the emergency-break benchmark matrix through the local debug typst.
# Usage: benchmark/scripts/render.sh <corpus-dir> <output-dir>
set -euo pipefail

FONT_NAME="TH Sarabun New"
FONT_PATH="/mnt/Datas/Champ/Coding/Repos/GOaT-hub/GOaT-Documents/themes/MWITypst-UNOF/assets/fonts"
TEXT_SIZE="16pt"
PAR_LEADING="0.65em"

# Characters Typst markup treats specially. Corpus text is escaped so that the
# rendered glyph stream matches the source file rather than a parsed variant.
ESCAPE_ARGS=(
  -e 's/\\/\\\\/g' -e 's/\$/\\\$/g' -e 's/#/\\#/g' -e 's/\*/\\*/g'
  -e 's/_/\\_/g' -e 's/@/\\@/g' -e 's/</\\</g' -e 's/>/\\>/g'
  -e 's/\[/\\[/g' -e 's/\]/\\]/g' -e 's/~/\\~/g' -e 's/`/\\`/g'
)
# Corpus lines beginning with one of these would become Typst list/term markup.
LEADING_MARKUP="^[-+=/<>*#]"

VARIANTS=(plain cut30 cut90)
MEASURES=(a4 narrow)

script_dir() { cd "$(dirname "${BASH_SOURCE[0]}")" && pwd; }
repo_root() { cd "$1/../.." && pwd; }

page_settings() {
  case "$1" in
    a4)    printf '#set page(paper: "a4", margin: (left: 1.5in, top: 1.5in, right: 1.0in, bottom: 1.0in))\n' ;;
    narrow) printf '#set page(width: 42mm, height: 297mm, margin: (top: 5mm, bottom: 5mm, left: 5mm, right: 5mm))\n' ;;
    *)     echo "unknown measure: $1" >&2; return 1 ;;
  esac
}

emergency_break_setting() {
  case "$1" in
    plain) return 0 ;;
    cut30) printf '#set par(emergency-break: 30%%)' ;;
    cut90) printf '#set par(emergency-break: 90%%)' ;;
    *)     echo "unknown variant: $1" >&2; return 1 ;;
  esac
}

assert_no_leading_markup() {
  local file="$1" hits
  hits=$(grep -n "$LEADING_MARKUP" "$file" || true)
  if [ -n "$hits" ]; then
    echo "corpus line starts with Typst list/heading markup, refusing to render: $file" >&2
    echo "$hits" >&2
    return 1
  fi
}

write_wrapper() {
  local measure="$1" variant="$2" source="$3" dest="$4"
  {
    page_settings "$measure"
    printf '#set text(font: "%s", lang: "th", size: %s)\n' "$FONT_NAME" "$TEXT_SIZE"
    printf '#set par(justify: true, leading: %s)\n' "$PAR_LEADING"
    emergency_break_setting "$variant"
    printf '\n\n'
    sed "${ESCAPE_ARGS[@]}" "$source"
  } > "$dest"
}

now_ms() { echo $(( $(date +%s%N) / 1000000 )); }

compile_one() {
  local measure="$1" stem="$2" variant="$3" source="$4" out_dir="$5" work_dir="$6"
  local wrapper="$work_dir/$measure-$stem-$variant.typ"
  local out_pdf="$out_dir/$measure/$stem/$variant.pdf"
  local start_ms end_ms rc
  mkdir -p "$out_dir/$measure/$stem"
  write_wrapper "$measure" "$variant" "$source" "$wrapper"
  start_ms=$(now_ms)
  rc=0
  "$TYPST" compile --font-path "$FONT_PATH" "$wrapper" "$out_pdf" || rc=$?
  end_ms=$(now_ms)
  if [ "$rc" -ne 0 ]; then
    echo "COMPILE FAILED rc=$rc measure=$measure corpus=$stem variant=$variant" >&2
    return "$rc"
  fi
  if [ ! -s "$out_pdf" ]; then
    echo "MISSING OR EMPTY PDF measure=$measure corpus=$stem variant=$variant path=$out_pdf" >&2
    return 1
  fi
  printf '%s\t%s\t%s\t%s\t%s\n' "$measure" "$stem" "$variant" "$((end_ms - start_ms))" "$(wc -c < "$out_pdf")" >> "$TIMINGS"
  printf '  %-8s %-28s %-6s %6d ms\n' "$measure" "$stem" "$variant" "$((end_ms - start_ms))"
}

render_matrix() {
  local corpus_dir="$1" out_dir="$2" work_dir="$3" file stem
  for file in "$corpus_dir"/*.txt; do
    stem=$(basename "$file" .txt)
    assert_no_leading_markup "$file"
    local measure variant
    for measure in "${MEASURES[@]}"; do
      for variant in "${VARIANTS[@]}"; do
        compile_one "$measure" "$stem" "$variant" "$file" "$out_dir" "$work_dir"
      done
    done
  done
}

write_manifest() {
  local corpus_dir="$1" out_dir="$2"
  local version commit rows
  version=$("$TYPST" --version)
  commit=$(git -C "$ROOT" rev-parse HEAD)
  rows=$(wc -l < "$TIMINGS")
  {
    printf '# Benchmark render manifest\n\n'
    printf 'Generated by `benchmark/scripts/render.sh`. Every number below is read\n'
    printf 'back from the run that produced the PDFs in this directory.\n\n'
    printf '## Environment\n\n'
    printf '| Field | Value |\n| --- | --- |\n'
    printf '| typst binary | `%s` |\n' "$TYPST"
    printf '| typst `--version` | `%s` |\n' "$version"
    printf '| git commit | `%s` |\n' "$commit"
    printf '| git branch | `%s` |\n' "$(git -C "$ROOT" rev-parse --abbrev-ref HEAD)"
    printf '| working tree at render time | %s |\n' "$(if [ -z "$(git -C "$ROOT" status --porcelain)" ]; then echo clean; else echo dirty; fi)"
    printf '| renders recorded | %s |\n' "$rows"
    printf '\n## Command template\n\n'
    printf '```\n'
    printf '%s compile --font-path %s <wrapper>.typ <out.pdf>\n' "$TYPST" "$FONT_PATH"
    printf '```\n\n'
    printf '| Slot | Value |\n| --- | --- |\n'
    printf '| wrapper | `%s/<measure>-<corpus-stem>-<variant>.typ` |\n' "$work_dir_desc"
    printf '| output | `%s/<measure>/<corpus-stem>/<variant>.pdf` |\n' "$out_dir"
    printf '\n## Typography (identical for every render)\n\n'
    printf '| Field | Value |\n| --- | --- |\n'
    printf '| font name | `%s` |\n' "$FONT_NAME"
    printf '| font path | `%s` |\n' "$FONT_PATH"
    printf '| language | `lang: "th"` |\n'
    printf '| size | `%s` |\n' "$TEXT_SIZE"
    printf '| justify | `true` |\n'
    printf '| leading | `%s` |\n' "$PAR_LEADING"
    printf '\n## Measures\n\n'
    printf '| Measure | Page settings | Text measure |\n| --- | --- | --- |\n'
    printf '| `a4` | `paper: "a4"`, `margin: (left: 1.5in, top: 1.5in, right: 1.0in, bottom: 1.0in)` | 210mm - 38.1mm - 25.4mm = 146.5mm |\n'
    printf '| `narrow` | `width: 42mm`, `height: 297mm`, `margin: 5mm` on all sides | 42mm - 10mm = 32mm |\n'
    printf '\nThe `a4` measure copies the MWIT report template in `GOaT-Documents/style.typ`\n'
    printf '(`MarginAcademic`). The `narrow` measure is chosen so the 32mm text measure is\n'
    printf 'roughly one fifth of the academic measure: at 16pt TH Sarabun New a long\n'
    printf 'unspaced Thai run regularly exceeds 32mm, so overfull lines occur in\n'
    printf '`plain` and the emergency-break threshold has something to act on.\n'
    printf '\n## Variants\n\n'
    printf '| Variant | `par(emergency-break:)` |\n| --- | --- |\n'
    printf '| `plain` | unset — no word is ever cut |\n'
    printf '| `cut30` | `30%%` — a word wider than 30%% of the measure may be cut |\n'
    printf '| `cut90` | `90%%` — a word wider than 90%% of the measure may be cut |\n'
    printf '\n## Corpus\n\n'
    printf '| File | Bytes | Lines |\n| --- | --- | --- |\n'
    local file
    for file in "$corpus_dir"/*.txt; do
      printf '| `%s` | %s | %s |\n' "$(basename "$file")" "$(wc -c < "$file")" "$(wc -l < "$file")"
    done
    printf '\nCorpus text is escaped for Typst markup before being inlined, so the\n'
    printf 'rendered glyphs match the source file byte for byte in content.\n'
    printf '\n## Render timings\n\n'
    printf 'Wall clock around `typst compile`, single run, milliseconds.\n\n'
    printf '| Measure | Corpus | Variant | Compile ms | PDF bytes |\n| --- | --- | --- | --- | --- |\n'
    awk -F'\t' '{printf "| `%s` | `%s` | `%s` | %s | %s |\n", $1, $2, $3, $4, $5}' "$TIMINGS"
  } > "$out_dir/MANIFEST.md"
}

main() {
  if [ "$#" -ne 2 ]; then
    echo "usage: $0 <corpus-dir> <output-dir>" >&2
    return 2
  fi
  local corpus_dir="$1" out_dir="$2" work_dir
  ROOT=$(repo_root "$(script_dir)")
  TYPST="$ROOT/target/debug/typst"
  work_dir_desc="<work-dir>"
  if [ ! -x "$TYPST" ]; then
    echo "missing typst binary: $TYPST" >&2
    return 1
  fi
  if [ ! -d "$FONT_PATH" ]; then
    echo "missing font directory: $FONT_PATH" >&2
    return 1
  fi
  if ! "$TYPST" fonts --font-path "$FONT_PATH" | grep -qa "$FONT_NAME"; then
    echo "font not found in $FONT_PATH: $FONT_NAME" >&2
    return 1
  fi
  mkdir -p "$out_dir"
  work_dir="$out_dir/.wrappers"
  work_dir_desc="${out_dir#"$ROOT"/}/.wrappers"
  mkdir -p "$work_dir"
  find "$work_dir" -name '*.typ' -delete
  TIMINGS="$work_dir/timings.tsv"
  : > "$TIMINGS"
  render_matrix "$corpus_dir" "$out_dir" "$work_dir"
  write_manifest "$corpus_dir" "$out_dir"
  printf '\nwrote %s renders and %s/MANIFEST.md\n' "$(wc -l < "$TIMINGS")" "$out_dir"
}

main "$@"
